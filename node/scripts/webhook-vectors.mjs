// Writes test/fixtures/webhook-vectors.json: known-good MYIDII-Signature headers for fixed inputs.
//
// signPayload below is copied line for line from platform/packages/contracts/src/signature.ts, which is
// what the platform uses to sign deliveries. If that file changes, copy it here again and re-run:
//
//   node scripts/webhook-vectors.mjs          # rewrite the fixture
//   node scripts/webhook-vectors.mjs --check  # fail if the committed fixture is out of date
//
// The SDK tests verify every vector with Myidii.webhooks.constructEvent, so the SDK and the platform
// cannot drift apart without a test failing.
import { createHmac } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

// --- from platform/packages/contracts/src/signature.ts ---
function signPayload(secret, body, timestamp = Math.floor(Date.now() / 1000)) {
  const v1 = createHmac("sha256", secret).update(`${timestamp}.${body}`).digest("hex");
  return `t=${timestamp},v1=${v1}`;
}
// --- end ---

const event = (type, data, extra = {}) =>
  JSON.stringify({ id: "evt_01JD3Q", object: "event", type, environment: "sandbox", created_at: "2026-11-01T12:00:00.000Z", data, ...extra });

const inputs = [
  {
    name: "session.completed",
    secret: "whsec_test_0123456789abcdef",
    timestamp: 1793534400,
    body: event("session.completed", {
      id: "ses_01JD3Q", object: "session", type: "liveness", environment: "sandbox", status: "passed",
      reference: "user_4821", attempts: 1, score: 0.98, photo_url: null,
      checks: [{ name: "head_turns", status: "passed", reason: "" }],
      created_at: "2026-11-01T11:59:00.000Z", decided_at: "2026-11-01T12:00:00.000Z",
    }),
  },
  { name: "wallet.low_balance", secret: "whsec_live_9f8e7d6c5b4a", timestamp: 1700000000, body: event("wallet.low_balance", { balance: 150, low_balance: 200 }, { environment: "live" }) },
  { name: "webhook.test pretty printed", secret: "whsec_test_pretty", timestamp: 1793534401, body: JSON.stringify(JSON.parse(event("webhook.test", {})), null, 2) + "\n" },
  { name: "non-ascii body", secret: "whsec_test_unicode", timestamp: 1793534402, body: event("session.completed", { reference: "Ọ̀sárùmẹ́n 👋 café" }) },
  { name: "secret with symbols", secret: "s3cr=t,with=commas and spaces", timestamp: 1793534403, body: event("session.expired", { id: "ses_x" }) },
];

const fixture = {
  note: "Generated by node/scripts/webhook-vectors.mjs using signPayload from platform/packages/contracts/src/signature.ts. Do not edit by hand.",
  scheme: "MYIDII-Signature: t=<unix seconds>,v1=<hex HMAC-SHA256 of \"<t>.<raw body>\" keyed with the endpoint secret>",
  vectors: inputs.map((v) => ({ ...v, header: signPayload(v.secret, v.body, v.timestamp) })),
};

const out = fileURLToPath(new URL("../test/fixtures/webhook-vectors.json", import.meta.url));
const text = JSON.stringify(fixture, null, 2) + "\n";
if (process.argv.includes("--check")) {
  if (readFileSync(out, "utf8") !== text) {
    console.error("webhook-vectors.json is out of date. Run: node scripts/webhook-vectors.mjs");
    process.exit(1);
  }
  console.log("webhook-vectors.json is up to date");
} else {
  writeFileSync(out, text);
  console.log(`wrote ${fixture.vectors.length} vectors to ${out}`);
}
